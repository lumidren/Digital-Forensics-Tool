#!/usr/bin/env python3
"""Aggregate parity/results/*.json into docs/PARITY.md.

Each result file follows parity/README.md. The table lists, per parser and per field, how many
records agreed with the reference implementation. Overall agreement is the ratio of agreeing
field comparisons to all field comparisons.
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = ROOT / "parity" / "results"
OUT = ROOT / "docs" / "PARITY.md"


def load() -> list[dict]:
    out = []
    for p in sorted(RESULTS.glob("*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        d.setdefault("parser", p.stem)
        out.append(d)
    return out


def pct(a: int, t: int) -> str:
    return f"{100.0 * a / t:.2f}%" if t else "n/a"


def render(results: list[dict]) -> str:
    lines = [
        "# Parser Parity Results",
        "",
        "Generated by `scripts/parity_report.py` from `parity/results/*.json`. Each row compares Veritas",
        "output with a reference implementation on public test data (plaso and dfvfs `test_data`,",
        "pinned by SHA-256 in `testdata/MANIFEST.json`). A field agrees when the normalized values are",
        "equal for the same record. CI fails if any field's ratio drops below `parity/baseline.json`.",
        "",
        "## Summary",
        "",
        "| Parser | Reference | Samples | Records (ours / ref) | Fields | Agreement |",
        "|---|---|---|---|---|---|",
    ]
    total_a = total_t = 0
    for d in results:
        fields = d.get("fields", {})
        a = sum(f["agree"] for f in fields.values())
        t = sum(f["total"] for f in fields.values())
        total_a += a
        total_t += t
        lines.append(f"| {d['parser']} | {d.get('reference', '')} | {len(d.get('samples', []))} | {d.get('records_ours', '')} / {d.get('records_reference', '')} | {len(fields)} | {pct(a, t)} |")
    lines += ["", f"**Overall field agreement: {pct(total_a, total_t)} over {total_t} comparisons.**", "", "## Field-level detail", ""]
    for d in results:
        lines += [f"### {d['parser']}", "", f"Reference: {d.get('reference', '')}", ""]
        if d.get("samples"):
            lines.append("Samples: " + ", ".join(f"`{s}`" for s in d["samples"][:20]) + (" ..." if len(d["samples"]) > 20 else ""))
            lines.append("")
        lines += ["| Field | Agree | Total | Ratio |", "|---|---|---|---|"]
        for name, f in sorted(d.get("fields", {}).items()):
            lines.append(f"| {name} | {f['agree']} | {f['total']} | {pct(f['agree'], f['total'])} |")
        if d.get("notes"):
            lines += ["", f"Notes: {d['notes']}"]
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    results = load()
    if not results:
        print("no parity results found", file=sys.stderr)
        return 1
    OUT.write_text(render(results), encoding="utf-8")
    print(f"wrote {OUT} ({len(results)} parsers)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
